def render(name: str) -> Path:
    source = (DOCS / name).read_text()
    diagrams = list(DIAGRAMS.get(name, []))

    def swap(_match: re.Match[str]) -> str:
        return diagrams.pop(0) if diagrams else ""

    source = re.sub(r"```mermaid\n.*?\n```", swap, source, flags=re.S)

    body = markdown.markdown(
        source,
        extensions=["tables", "fenced_code", "codehilite", "attr_list", "md_in_html"],
        extension_configs={"codehilite": {"noclasses": True, "pygments_style": "friendly"}},
    )
    page = (
        f"<!DOCTYPE html><html><head><meta charset='utf-8'>"
        f"<style>{CSS}</style></head><body>{body}</body></html>"
    )
    html_path = DOCS / f".{name}.html"
    html_path.write_text(page)

    chrome = next(iter(glob.glob("/opt/pw-browsers/chromium*/chrome-linux/chrome")), None)
    if not chrome:
        sys.exit("headless chromium not found")

    pdf_path = DOCS / name.replace(".md", ".pdf")
    subprocess.run(
        [
            chrome,
            "--headless",
            "--disable-gpu",
            "--no-sandbox",
            "--no-pdf-header-footer",
            "--virtual-time-budget=8000",
            f"--print-to-pdf={pdf_path}",
            f"file://{html_path}",
        ],
        check=True,
        capture_output=True,
    )
    html_path.unlink()
    return pdf_path


def main() -> None:
    for name in ("ARCHITECTURE.md", "IMPLEMENTATION.md"):
        path = render(name)
        print(f"wrote {path.relative_to(ROOT)}  ({path.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
