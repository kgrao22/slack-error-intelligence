# --- a very small ranked-flow SVG layout engine ----------------------------


def flow(
    ranks: list[list[tuple[str, str]]],
    *,
    width: int = 860,
    box_h: int = 54,
    gap_y: int = 34,
    gap_x: int = 16,
    caption: str = "",
) -> str:
    """Lay out ranks of (label, colour) boxes top-to-bottom with arrows between.

    Labels may contain a newline to wrap. Colour is a fill; an empty string means
    an outlined box. Arrows connect the centre of each rank to the next.
    """
    pad = 12
    height = len(ranks) * box_h + (len(ranks) - 1) * gap_y + pad * 2 + (22 if caption else 0)
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
        f'width="100%" role="img" font-family="system-ui, -apple-system, sans-serif">',
        '<defs><marker id="ar" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" '
        f'markerHeight="7" orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="{LINE}"/>'
        "</marker></defs>",
    ]

    y = pad
    centres: list[tuple[float, float]] = []
    for rank in ranks:
        n = len(rank)
        box_w = (width - pad * 2 - gap_x * (n - 1)) / n
        x = pad
        row_centres = []
        for label, colour in rank:
            fill = colour or "#ffffff"
            stroke = colour or LINE
            text_fill = "#ffffff" if colour else INK
            out.append(
                f'<rect x="{x:.1f}" y="{y}" width="{box_w:.1f}" height="{box_h}" rx="8" '
                f'fill="{fill}" stroke="{stroke}" stroke-width="1.2"/>'
            )
            lines = label.split("\n")
            start = y + box_h / 2 - (len(lines) - 1) * 8
            for i, line in enumerate(lines):
                size = 12.5 if i == 0 else 11
                weight = "600" if i == 0 else "400"
                opacity = "1" if i == 0 else "0.85"
                out.append(
                    f'<text x="{x + box_w / 2:.1f}" y="{start + i * 16:.1f}" '
                    f'text-anchor="middle" dominant-baseline="middle" font-size="{size}" '
                    f'font-weight="{weight}" fill="{text_fill}" opacity="{opacity}">'
                    f"{html_mod.escape(line)}</text>"
                )
            row_centres.append((x + box_w / 2, y))
            x += box_w + gap_x
        centres.append((sum(c[0] for c in row_centres) / len(row_centres), y))
        y += box_h + gap_y

    for i in range(len(centres) - 1):
        x1, y1 = centres[i]
        x2, _ = centres[i + 1]
        top = y1 + box_h
        bottom = top + gap_y - 4
        out.append(
            f'<path d="M{x1:.1f},{top} L{x1:.1f},{(top + bottom) / 2:.1f} '
            f'L{x2:.1f},{(top + bottom) / 2:.1f} L{x2:.1f},{bottom:.1f}" fill="none" '
            f'stroke="{LINE}" stroke-width="1.4" marker-end="url(#ar)"/>'
        )

    if caption:
        out.append(
            f'<text x="{width / 2}" y="{height - 6}" text-anchor="middle" font-size="11" '
            f'fill="{MUTED}">{html_mod.escape(caption)}</text>'
        )
    out.append("</svg>")
    return "".join(out)


def table_diagram(title: str, rows: list[tuple[str, str]]) -> str:
    """An entity/relationship rendering as a definition block. In print this
    reads better than a boxes-and-crows-feet drawing, which needs zoom."""
    body = "".join(
        f'<tr><td class="ent">{html_mod.escape(a)}</td>'
        f'<td class="rel">{html_mod.escape(b)}</td></tr>'
        for a, b in rows
    )
    return (
        f'<table class="erd"><caption>{html_mod.escape(title)}</caption>'
        f"<tbody>{body}</tbody></table>"
    )


