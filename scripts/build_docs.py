"""Render the documents in docs/ to print-quality PDF.

Mermaid stays in the Markdown, because GitHub renders it natively and the source
should remain the single copy of the diagram. For PDF the npm mermaid bundle is
not reachable from this environment, so each fenced ``mermaid`` block is replaced
by a hand-laid SVG from `DIAGRAMS` below, in document order. The SVGs are
generated by a small ranked-flow layout helper rather than drawn by hand, so
adding a diagram is a data change rather than a drawing exercise.

    python scripts/build_docs.py

Requires headless Chromium (present in this environment at
/opt/pw-browsers/chromium-*/chrome-linux/chrome) for the HTML → PDF step.
"""

